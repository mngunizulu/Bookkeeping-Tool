def normalize_language(language: str | None) -> str:
    return language if language in LANGUAGES else "en"


def tr(key: str, language: str = "en", **kwargs) -> str:
    lang = normalize_language(language)
    value = STRINGS.get(lang, {}).get(key, STRINGS["en"].get(key, key))
    return value.format(**kwargs) if kwargs else value


def category_label(name: str, language: str) -> str:
    return CATEGORY_DE.get(name, name) if normalize_language(language) == "de" else name


def kind_label(kind: str, language: str) -> str:
    return tr(kind if kind in {"income", "expense", "all"} else kind, language)


def payment_label(value: str, language: str) -> str:
    mapping = {"Bank": "bank", "Card": "card", "Cash": "cash", "PayPal": "PayPal", "Other": "other"}
    key = mapping.get(value, value)
    return key if key == "PayPal" else tr(key, language)


def document_type_label(value: str, language: str) -> str:
    return tr(value, language) if value in {"receipt", "receipt_photo", "unfiled", "unfiled_photo"} else value
